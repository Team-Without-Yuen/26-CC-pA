module mini_top(a, b, c, spare, clk, rst_n, bus, y, z, q, direct_out, bus_out);
input a, b, c, spare, clk, rst_n;
input [1:0] bus;
output y, z, q, direct_out, bus_out;
wire n_and, n_or, n_not, n_xor, n_nand, n_nor, n_xnor, n_buf;
wire d0, d1, d2, d3, d4, d5, d6, d7, d8, d9;
wire d10, d11, d12, d13, d14, d15, d16, d17, d18, d19;
wire d20, d21, d22, d23, d24;

and g_and(n_and, a, b);
or g_or(n_or, n_and, c);
not g_not(n_not, n_or);
xor g_xor(n_xor, n_not, b);
nand g_nand(n_nand, n_xor, 1'b1);
nor g_nor(n_nor, n_nand, 1'b0);
xnor g_xnor(n_xnor, n_nor, a);
buf g_buf(n_buf, n_xnor);
buf g_y(y, n_buf);
buf g_z(z, n_or);
buf g_direct(direct_out, a);
xor g_bus(bus_out, bus[0], bus[1]);
dff ff1(.D(n_buf), .CK(clk), .RN(rst_n), .SN(1'b1), .Q(q));

buf d_buf0(d0, spare);
buf d_buf1(d1, d0);
buf d_buf2(d2, d1);
buf d_buf3(d3, d2);
buf d_buf4(d4, d3);
buf d_buf5(d5, d4);
buf d_buf6(d6, d5);
buf d_buf7(d7, d6);
buf d_buf8(d8, d7);
buf d_buf9(d9, d8);
buf d_buf10(d10, d9);
buf d_buf11(d11, d10);
buf d_buf12(d12, d11);
buf d_buf13(d13, d12);
buf d_buf14(d14, d13);
buf d_buf15(d15, d14);
buf d_buf16(d16, d15);
buf d_buf17(d17, d16);
buf d_buf18(d18, d17);
buf d_buf19(d19, d18);
buf d_buf20(d20, d19);
buf d_buf21(d21, d20);
buf d_buf22(d22, d21);
buf d_buf23(d23, d22);
buf d_buf24(d24, d23);
endmodule
